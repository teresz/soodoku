const DICT: Record<Lang, Record<Key, string>> = { pl: PL, en: EN };
const KEY = 'kratka.lang.v1'; // prefiks z czasów nazwy „Kratka”, żeby nie gubić zapisów graczy

function initialLang(): Lang {
  try {
    const v = localStorage.getItem(KEY);
    if (v === 'pl' || v === 'en') return v;
  } catch { /* bez localStorage zostaje domyślny */ }
  return 'pl';
}

let lang: Lang = initialLang();
const listeners: (() => void)[] = [];

export const getLang = () => lang;
/** Locale do liczb (separator tysięcy, przecinek dziesiętny). */
export const locale = () => (lang === 'pl' ? 'pl-PL' : 'en-GB');
export const num = (n: number) => n.toLocaleString(locale());

export function t(key: Key, vars: Record<string, string | number> = {}) {
  return DICT[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

/** Klucze budowane w locie (np. `${mode.id}.name`); nieznany klucz wraca jako on sam. */
export const tk = (key: string, vars?: Record<string, string | number>) =>
  key in PL ? t(key as Key, vars) : key;

export function setLang(next: Lang) {
  if (next === lang) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* trudno */ }
  applyStatic();
  listeners.forEach((fn) => fn());
}

export const onLangChange = (fn: () => void) => { listeners.push(fn); };

/** Podmienia stałe teksty z index.html. */
export function applyStatic(root: ParentNode = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((e) => { e.textContent = tk(e.dataset.i18n!); });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((e) => e.setAttribute('aria-label', tk(e.dataset.i18nAria!)));
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((e) => { e.title = tk(e.dataset.i18nTitle!); });
}

